// Hidratar inmediatamente desde caché local para renderizado instantáneo (Stale-While-Revalidate)
try {
  const cachedProducts = localStorage.getItem('cm_products');
  if (cachedProducts) {
    window.CM_DATA.productos = JSON.parse(cachedProducts);
  }
} catch (e) {
  console.warn('No se pudo precargar la caché de productos:', e);
}

// Cargar productos desde la base de datos MySQL (con fallback local)
async function loadProductsFromDB() {
  try {
    const res = await fetch('backend/api_productos.php');
    const json = await res.json();
    if (json && !json.error && json.data && json.data.length > 0) {
      // Cruzar con specs locales para no perder la información detallada de specs
      const localProducts = window.CM_DATA.productos;
      const mergedProducts = json.data.map(dbProd => {
        const localProd = localProducts.find(p => p.id === dbProd.id);
        return {
          ...dbProd,
          specs: localProd ? localProd.specs : {}
        };
      });
      
      const oldJSON = localStorage.getItem('cm_products');
      const newJSON = JSON.stringify(mergedProducts);
      
      // Si la caché está vacía o el contenido es diferente, actualizar y re-renderizar
      if (oldJSON !== newJSON) {
        window.CM_DATA.productos = mergedProducts;
        localStorage.setItem('cm_products', newJSON);
        
        if (typeof renderPage === 'function') {
          const page = new URLSearchParams(window.location.search).get('page') || 'home';
          renderPage(page);
        }
      }
    }
  } catch (e) {
    console.warn('No se pudo conectar a la base de datos MySQL. Usando datos locales de respaldo.', e);
  }
}
loadProductsFromDB();
